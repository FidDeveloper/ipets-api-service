#!/bin/bash
# The MySQL entrypoint sources this file; isolate shell options and credentials.
# Idempotent: also run against an existing volume with `docker compose exec mysql bash /docker-entrypoint-initdb.d/01-init.sh`.
(
set -eu
export MYSQL_PWD="$MYSQL_ROOT_PASSWORD"
# database runtime-user runtime-password migrator-password
for spec in "auth_db auth AUTH" "core_db pet CORE" "document_db document DOCUMENT" "notification_db notification NOTIFICATION"; do
  set -- $spec
  db=$1; user=$2; runtime_var="MYSQL_${3}_PASSWORD"; migrator_var="MYSQL_${3}_MIGRATOR_PASSWORD"
  runtime="${!runtime_var}"; migrator="${!migrator_var}"
  for value in "$runtime" "$migrator"; do
    [[ "$value" =~ ^[a-f0-9]{48}$ ]] || { echo 'Database password must be generated by setup_local.py' >&2; exit 1; }
  done
  mysql -uroot <<EOSQL
CREATE DATABASE IF NOT EXISTS ${db} CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE USER IF NOT EXISTS '${user}'@'%' IDENTIFIED BY '${runtime}';
GRANT SELECT, INSERT, UPDATE, DELETE ON ${db}.* TO '${user}'@'%';
CREATE USER IF NOT EXISTS '${user}_migrator'@'%' IDENTIFIED BY '${migrator}';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, DROP, REFERENCES ON ${db}.* TO '${user}_migrator'@'%';
EOSQL
done
)
