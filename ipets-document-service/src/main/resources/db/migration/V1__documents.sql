CREATE TABLE files (
  id CHAR(36) NOT NULL PRIMARY KEY, owner_id CHAR(36) NOT NULL, mime VARCHAR(40) NOT NULL, size_bytes BIGINT NOT NULL, sha256 CHAR(64) NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX ix_files_owner (owner_id)
);
CREATE TABLE documents (
  id CHAR(36) NOT NULL PRIMARY KEY, owner_id CHAR(36) NOT NULL, pet_id CHAR(36) NOT NULL, version BIGINT NOT NULL DEFAULT 1,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3), deleted_at TIMESTAMP(3) NULL,
  name VARCHAR(200) NOT NULL, mime VARCHAR(100) NOT NULL, doc_date DATE NOT NULL, status VARCHAR(20) NOT NULL, sample BOOLEAN NOT NULL DEFAULT FALSE,
  file_id CHAR(36) NOT NULL, INDEX ix_documents_owner (owner_id, updated_at)
);
CREATE TABLE drafts (
  id CHAR(36) NOT NULL PRIMARY KEY, owner_id CHAR(36) NOT NULL, pet_id CHAR(36) NOT NULL, version BIGINT NOT NULL DEFAULT 1,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3), deleted_at TIMESTAMP(3) NULL,
  document_ids JSON NOT NULL, created DATE NOT NULL, engine VARCHAR(12) NOT NULL, card_pet_name VARCHAR(200) NOT NULL DEFAULT '',
  warnings JSON NOT NULL, draft_rows JSON NOT NULL, INDEX ix_drafts_owner (owner_id, updated_at)
);
CREATE TABLE scans (
  id CHAR(36) NOT NULL PRIMARY KEY, owner_id CHAR(36) NOT NULL, pet_id CHAR(36) NOT NULL, status VARCHAR(16) NOT NULL, stage VARCHAR(16) NOT NULL,
  message VARCHAR(300) NULL, attempts INT NOT NULL DEFAULT 0, draft JSON NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX ix_scans_owner (owner_id), INDEX ix_scans_status (status, updated_at)
);
CREATE TABLE scan_pages (
  scan_id CHAR(36) NOT NULL, page_no INT NOT NULL, file_id CHAR(36) NOT NULL, mime VARCHAR(40) NOT NULL, size_bytes BIGINT NOT NULL,
  sha256 CHAR(64) NOT NULL, uploaded BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (scan_id, page_no), CONSTRAINT fk_pages_scan FOREIGN KEY (scan_id) REFERENCES scans (id) ON DELETE CASCADE
);
